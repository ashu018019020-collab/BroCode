import { useEffect, useMemo, useState } from 'react';
import { Link, useLocation } from 'react-router-dom';
import { BookMarked, BookOpen, ChevronDown, ChevronUp, Code2, FileText, ListChecks, Map as MapIcon, Mic2, Puzzle, ShieldCheck, Users } from 'lucide-react';
import { useCurriculum } from '../../core/data/curriculum';
import { TYPE_LABEL } from '../../core/data/questions';
import type { QuestionType } from '../../core/data/schema';
import { usePlaybookIndex, usePlaybookItems, type PbChapter } from '../../core/data/playbook';
import { ACTION_OF_TYPE, STAGE_OF_TYPE, type PbItem } from '../../core/assessment/playbook';
import { stepOfChapter } from '../../core/learning/roadmap';

/**
 * The V15 "AI Engineer Master — Systems + Interview Playbook" chapter index.
 *
 * The playbook's 477 practice items do NOT live on this page: every one of them was merged into the
 * bank of the section it belongs to (`npm run questions:playbook`), so there is exactly one home
 * per question and one place to save an answer. What this page owns is the DOCUMENT view — the
 * chapter list, what each chapter contributed, which sections received it, and the page in the
 * playbook PDF it came from.
 * * Both files are generated by the pipeline, never hand-written:
 *   public/generated/playbook/manifest.json — the chapter index, written by scripts/playbook.cjs
 *   public/generated/playbook/items.json    — a derived view of the bank items, written by the import step
 *
 * The manifest's SHAPE and the two loaders live in `src/core/data/playbook.ts`, and the item→stage
 * routing in `src/core/assessment/playbook.ts`: the Learning Path renders the same contract per track, so
 * a second copy of the types here is exactly how the two views would drift apart.
 *
 * CHAPTER NUMBERS ARE THE DOCUMENT'S, NOT THE ROAD'S. This page is the PDF's own table of
 * contents, so its rows are numbered 01–36 in print order — and the order a learner should read
 * them in is a different sequence, owned by `engine/roadmap.ts` and rendered on the Learning Path.
 * Every row therefore names the STEP it is read at and links there, so the two views cross-
 * reference instead of disagreeing: chapter 18 shows "Step 35", not "chapter 18 of 36".
 */

/**
 * One tone per chapter.
 *
 * The index is 20 rows of ONE document, not 20 kinds of thing, so colour here is a reading aid
 * rather than a category: what matters is that no two NEIGHBOURING chapters share a hue, which is
 * what makes a 20-row list scannable. Ten tones cycle, so chapter 01 and chapter 11 repeat — and
 * the tone never carries information on its own, so a repeat costs nothing.
 */
const CH_TONES = ['cyan', 'violet', 'blue', 'fuchsia', 'green', 'amber', 'purple', 'orange', 'gold', 'red'];
const toneOfChapter = (no: string) => CH_TONES[(Number(no) - 1 + CH_TONES.length) % CH_TONES.length];

/**
 * The glyph, unlike the colour, IS a category — and it is derived from what the chapter actually
 * contributed (`byType`, straight out of the manifest), never assigned by hand: a chapter full of
 * interview questions gets the mic, a coding-lab chapter gets the brackets, a chapter with nothing
 * in it is a concept chapter and reads the book. Re-routing the import could not make this wrong.
 */
const GLYPH: Record<string, typeof Mic2> = {
  interview: Mic2, checkpoint: ListChecks, coding: Code2, defense: ShieldCheck, logic: Puzzle, theory: BookOpen,
};
const glyphOf = (ch: PbChapter) => {
  const top = Object.entries(ch.byType).sort((a, b) => b[1] - a[1])[0]?.[0];
  return (top ? GLYPH[top] : undefined) ?? BookOpen;
};

export default function Playbook() {
  const index = usePlaybookIndex();
  const items = usePlaybookItems();
  const { sections } = useCurriculum();
  // A bank item's "ch.18" chip deep-links here as /playbook#18, so the chapter it came from is
  // already open. Without a hash nothing is expanded — 36 open chapters would be a wall of text.
  const loc = useLocation();
  const [open, setOpen] = useState<string | null>(() => loc.hash.replace('#', '') || null);
  // Also on change, not only at mount: a ch.18 chip clicked while this page is already open is a
  // same-document navigation, which would otherwise leave the previously expanded chapter showing.
  //
  // The deep link scrolls to its chapter, and this is the ONLY thing left that does: the strip of
  // 01–36 chips that used to sit under the heading was the other caller, and it duplicated both the
  // numbers and the names already on the rail below. Two details are deliberate —
  //
  //  · One frame later, so the measurement happens AFTER the chapter that was open has collapsed.
  //    Scrolling in the same tick aims at a layout that is about to move. Measured in the preview
  //    window: `requestAnimationFrame` there runs at roughly one call a second (an unfocused window
  //    is throttled), so the jump can land up to ~0.9 s after the click. It always lands — do not
  //    read the delay as a broken deep link.
  //  · Instant, never `behavior: 'smooth'`. Measured: a smooth scroll is a no-op in the Electron
  //    preview (the very same call reports `scrollTop: 0` afterwards), so a smooth jump would look
  //    like nothing had happened at all. An instant jump lands exactly, everywhere.
  useEffect(() => {
    const h = loc.hash.replace('#', '');
    if (!h) return;
    setOpen(h);
    requestAnimationFrame(() => document.getElementById(`ch-${h}`)?.scrollIntoView({ block: 'center' }));
  }, [loc.hash]);

  const byChapter = useMemo(() => {
    const map = new Map<string, PbItem[]>();
    for (const it of items?.items ?? []) {
      const list = map.get(it.chapter);
      if (list) list.push(it); else map.set(it.chapter, [it]);
    }
    return map;
  }, [items]);

  /**
   * What the banks actually hold per type. The manifest's own breakdown counts one question that
   * was refused on import as a cross-bank duplicate, and this page describes the app, so the
   * merged view wins whenever items.json is here.
   */
  const typeChips = useMemo(() => {
    const merged = new Map<string, number>();
    for (const it of items?.items ?? []) merged.set(it.type, (merged.get(it.type) ?? 0) + 1);
    const source: [string, number][] = merged.size
      ? [...merged.entries()]
      : Object.entries(index?.totals.byType ?? {});
    return source.sort((a, b) => b[1] - a[1]);
  }, [items, index]);

  if (!index) return <div className="loading">Playbook index load ho raha hai…</div>;

  const t = index.totals;
  /** Denominators for the header chips, and for a chapter's share of the whole document. */
  const totalItems = items?.count ?? t.items;
  const maxItems = Math.max(1, ...index.chapters.map((c) => c.items));
  const labChapter = index.chapters.find((c) => c.no === '15');
  const projectChapter = index.chapters.find((c) => c.no === '17');

  return (
    <div>
      {/* HEADER — what this document is, and what it added. */}
      <div className="card glow fadeup">
        <div className="row spread" style={{ flexWrap: 'wrap', gap: 10 }}>
          <div>
            <div className="row small muted" style={{ gap: 6, marginBottom: 6 }}>
              <span className="chip">SECOND SOURCE</span>
              <span className="chip">{index.pages} pages</span>
              <span className="chip">{index.chapters.length} chapters</span>
              {/* What the banks actually took, once items.json is here. The manifest's own count is
                  the document's offer (one question was refused as a cross-bank duplicate), so the
                  two differ by one and the merged figure is the one that describes this app. */}
              <span className="chip">{items?.count ?? t.items} items imported</span>
            </div>
            {/* The emoji stays outside the gradient-clipped span: `background-clip: text` would
                otherwise repaint it as a gradient silhouette instead of an emoji. */}
            <h1 style={{ margin: '4px 0' }}><span aria-hidden>📘</span> <span className="pb-title">AI Engineer Master Playbook V15</span></h1>
            <p className="muted small" style={{ maxWidth: 720, margin: 0 }}>
              {index.source.replace(/\.pdf$/, '').replace(/_/g, ' ')} — pichhle guide ke saath ye doosra source hai.
              Har item section ke apne bank me gaya hai (duplicate text skip karke), to practise ek hi jagah hota hai.
            </p>
          </div>
        </div>

        <div className="row" style={{ marginTop: 10, flexWrap: 'wrap', gap: 6 }}>
          {typeChips.map(([type, n]) => (
            <span key={type} className="chip">
              {TYPE_LABEL[type as QuestionType] ?? type}: <b>{n}</b>
            </span>
          ))}
        </div>

        <div className="row" style={{ marginTop: 10, flexWrap: 'wrap' }}>
          <Link className="btn small primary" to="/interview"><Mic2 size={13} /> Interview Mode me “Playbook V15” source</Link>
          <Link className="btn small" to="/questions"><ListChecks size={13} /> Question Bank (sab questions)</Link>
          <Link className="btn small" to="/pdf/playbook"><FileText size={13} /> Playbook PDF padho</Link>
          {labChapter && <Link className="btn small" to={`/lesson/${labChapter.sectionId}/coding`}>💻 {t.labs} coding labs</Link>}
          {projectChapter && <Link className="btn small" to={`/lesson/${projectChapter.sectionId}/mini`}>🏗️ {t.miniProjectBlueprints + t.miniProjectCapstones} mini projects</Link>}
        </div>

        <p className="small muted" style={{ marginBottom: 0 }}>
          {t.methodAnswers} prompts (checkpoint + production scenario) ke aage document ne model answer ki jagah apna method diya hai —
          wahi verbatim rakha gaya hai aur <span className="chip">method-answer</span> tag lagaya gaya hai. Koi answer invent nahi kiya gaya.
        </p>
      </div>

      {/* CHAPTER INDEX — each chapter gets its own section, opened on demand. */}
      <div className="card" style={{ marginTop: 12 }}>
        <div className="row spread">
          <h3 className="row" style={{ gap: 8, margin: 0 }}><BookMarked size={16} color="var(--cyan)" /> Chapter index</h3>
          <span className="small muted">
            Chapter kholo → uske items, unka section aur PDF page ·
            {' '}<Link to="/path">roadmap ke 36 steps me dekho →</Link>
          </span>
        </div>

        {/*
          The document, as one line.

          A chapter index is a SEQUENCE — ch.18 only makes sense between 17 and 19 — and the boxes
          were a stack of rows that only said "here are 36 things". They now sit on the same rail as
          the track roadmap and the extra paths (`.rmap-*`): the number is the node ON the line, the
          spine runs through the whole 94-page document, and an arrowhead points into the next
          chapter. The number moved out of the box and into the rail rather than being printed
          twice; the box keeps the chapter's own tone, its glyph, its share bar and its PDF page.

          Progressive disclosure is unchanged: a node is one line until it is opened. There is no
          jump strip above any more — it printed the same 01–36 as the rail, so it was a second copy
          of the numbers rather than a way to navigate. Every chapter is one row below, in order.
        */}
        <div className="tree rmap rmap-doc" role="tree" aria-label="Playbook chapters">
          {index.chapters.map((ch, ci) => {
            const isOpen = open === ch.no;
            const Glyph = glyphOf(ch);
            const own = byChapter.get(ch.no) ?? [];
            const sec = sections.find((s) => s.id === ch.sectionId);
            const targets = Object.entries(ch.sections).sort((a, b) => b[1] - a[1]);
            const last = ci === index.chapters.length - 1;
            return (
              <div
                key={ch.no}
                className={`rmap-step rmap-doc-step tone-${toneOfChapter(ch.no)}${isOpen ? ' open' : ''}`}
              >
                <div className="rmap-rail" aria-hidden="true">
                  <span className="rmap-dot">{ch.no}</span>
                  {!last && <span className="rmap-line" />}
                  {!last && <span className="rmap-arrow"><ChevronDown size={12} /></span>}
                </div>
                <div
                  id={`ch-${ch.no}`}
                  className={`tree-ch ch-box${isOpen ? ' open' : ''}`}
                  role="treegroup"
                  aria-expanded={isOpen}
                >
                  <button
                    className="tree-row ch ch-head"
                    aria-expanded={isOpen}
                    onClick={() => setOpen(isOpen ? null : ch.no)}
                  >
                    <span className="ch-ic"><Glyph size={16} /></span>
                    {/* `ch-title` is the flexible one, so a long chapter name truncates instead of
                        pushing the count, the bar and the PDF page off the row. */}
                    <b className="ch-title" style={{ textAlign: 'left' }}>{ch.title}</b>
                    {ch.items > 0
                      ? <>
                          <span className="ch-sub">{ch.items} items · {Object.keys(ch.sections).length} sections</span>
                          {/* Share of the biggest chapter, so 2 items and 205 items are both visible. */}
                          <span className="ch-share" title={`${ch.items} of ${totalItems} imported items`}>
                            <i style={{ width: `${Math.max(5, Math.round((ch.items / maxItems) * 100))}%` }} />
                          </span>
                        </>
                      : <span className="ch-sub">concept chapter{sec ? ` · lesson ${String(sec.no).padStart(2, '0')}` : ''}</span>}
                    {/* Where this chapter sits ON THE ROAD — hidden on narrow screens, where the
                        head has no room left, and always present in the opened panel below. */}
                    {(() => {
                      const step = stepOfChapter(ch.no);
                      return step === null ? null : (
                        <Link
                          className="chip ch-step"
                          to={`/path#s${step}`}
                          onClick={(e) => e.stopPropagation()}
                          title={`Roadmap step ${step} — yahan ye chapter padha jata hai`}
                        >
                          <MapIcon size={11} /> Step {String(step).padStart(2, '0')}
                        </Link>
                      );
                    })()}
                    <Link className="chip" to={`/pdf/playbook/${ch.pdfPage}`} onClick={(e) => e.stopPropagation()}>
                      <FileText size={11} /> p.{ch.pdfPage}
                    </Link>
                    <span className="ch-chev">{isOpen ? <ChevronUp size={15} /> : <ChevronDown size={15} />}</span>
                  </button>

                  {isOpen && (
                    <div className="tree-topics" role="treeitem">
                      {ch.items === 0 ? (
                        <div className="tree-footer">
                          <p className="small muted" style={{ margin: '0 0 6px' }}>
                            Is chapter me practice items nahi hain — ye concept/playbook chapter hai.
                            {sec ? ` Iska lesson section ${String(sec.no).padStart(2, '0')} · ${sec.title} hai.` : ''}
                          </p>
                          <div className="row" style={{ flexWrap: 'wrap' }}>
                            {sec && <Link className="btn small primary" to={`/lesson/${sec.id}/learn`}>Lesson kholo → {sec.title}</Link>}
                            <Link className="btn small" to={`/pdf/playbook/${ch.pdfPage}`}>PDF p.{ch.pdfPage}</Link>
                          </div>
                        </div>
                      ) : (
                        <>
                          {/* Sample of what this chapter contributed. Practice happens in the bank, so
                              every row links there instead of keeping a second, unsaveable copy here. */}
                          {own.slice(0, 6).map((it) => (
                            <Link
                              key={it.id}
                              className="tree-row topic"
                              // `playbook=1` pre-ticks the bank's "sirf Playbook V15" filter, so the link
                              // opens the playbook items of that section rather than 500 curriculum ones.
                              to={`/questions?section=${it.sectionId}&playbook=1`}
                              title={`${it.question} — ${it.sectionTitle} ke bank me practice karo`}
                            >
                              <span className="mark">{it.type === 'coding' ? '💻' : it.type === 'checkpoint' ? '✅' : '🎤'}</span>
                              <span style={{ flex: 1, textAlign: 'left' }}>{it.question}</span>
                              <span className="chip">{ACTION_OF_TYPE[it.type] ?? it.type}</span>
                              {it.selfGrade && <span className="chip" title="Document ne method diya hai, model answer nahi">method</span>}
                            </Link>
                          ))}
                          {own.length > 6 && (
                            <div className="tree-row topic" style={{ cursor: 'default' }}>
                              <span className="mark">＋</span>
                              <span className="muted" style={{ flex: 1 }}>… aur {own.length - 6} items us section ke bank me</span>
                            </div>
                          )}

                          <div className="tree-footer">
                            <div className="row" style={{ gap: 6, flexWrap: 'wrap' }}>
                              {Object.entries(ch.byType).map(([type, n]) => (
                                <span key={type} className="chip">{ACTION_OF_TYPE[type] ?? type}: {n}</span>
                              ))}
                              {targets.map(([sid, n]) => {
                                const s = sections.find((x) => x.id === sid);
                                return (
                                  <span key={sid} className="chip" title={`${n} item(s) yahan gaye`}>
                                    <Users size={11} /> {s ? `${String(s.no).padStart(2, '0')} ${s.title.split(' ')[0]}` : sid}: {n}
                                  </span>
                                );
                              })}
                            </div>
                            <div className="row" style={{ marginTop: 8, flexWrap: 'wrap' }}>
                              {stepOfChapter(ch.no) !== null && (
                                <Link className="btn small" to={`/path#s${stepOfChapter(ch.no)}`}>
                                  <MapIcon size={12} /> Roadmap step {String(stepOfChapter(ch.no)).padStart(2, '0')}
                                </Link>
                              )}
                              <Link className="btn small primary" to={`/lesson/${ch.sectionId}/${STAGE_OF_TYPE[Object.keys(ch.byType)[0] ?? 'interview'] ?? 'interview'}`}>
                                Practice shuru karo →
                              </Link>
                              <Link className="btn small" to={`/questions?section=${ch.sectionId}&playbook=1`}>Question Bank (playbook items)</Link>
                              {targets.slice(0, 3).map(([sid]) => {
                                const s = sections.find((x) => x.id === sid);
                                return s ? <Link key={sid} className="btn small" to={`/lesson/${sid}/interview`}>{String(s.no).padStart(2, '0')} interview</Link> : null;
                              })}
                            </div>
                          </div>
                        </>
                      )}
                    </div>
                  )}
                </div>
              </div>
            );
          })}
        </div>
      </div>

      <p className="small muted" style={{ marginTop: 10 }}>
        Index pipeline se banta hai: <code>npm run questions:playbook</code> (banks + is page ka index + items view, teeno ek saath).
        Playbook PDF ka page number is page ke apne PDF ka hai — guide.pdf ke deep links waise hi kaam karte hain.
      </p>
    </div>
  );
}
